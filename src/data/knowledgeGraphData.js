// ── Graph Data Accessors ──

export function getNodeById(id) {
  return GRAPH_NODES.find((node) => node.id === id || node.slug === id);
}

export function getConnectedNodes(nodeId) {
  const node = getNodeById(nodeId);
  if (!node) return [];

  const connections = [];

  GRAPH_LINKS.forEach((link) => {
    if (link.source === node.id) {
      const targetNode = getNodeById(link.target);
      if (targetNode) {
        connections.push({
          node: targetNode,
          weight: link.weight,
          label: link.label,
          rationale: link.rationale,
          direction: 'outgoing',
        });
      }
    } else if (link.target === node.id) {
      const sourceNode = getNodeById(link.source);
      if (sourceNode) {
        connections.push({
          node: sourceNode,
          weight: link.weight,
          label: link.label,
          rationale: link.rationale,
          direction: 'incoming',
        });
      }
    }
  });

  return connections.sort((a, b) => b.weight - a.weight);
}

export function getNodesByDomain(domainId) {
  if (!domainId || domainId === 'all') return GRAPH_NODES;
  return GRAPH_NODES.filter((node) => node.domain === domainId);
}

export function searchGraphNodes(query) {
  if (!query || typeof query !== 'string') return [];
  const q = query.trim().toLowerCase();
  return GRAPH_NODES.filter((node) =>
    node.title.toLowerCase().includes(q) ||
    node.domainName.toLowerCase().includes(q) ||
    node.summary.toLowerCase().includes(q)
  );
}
